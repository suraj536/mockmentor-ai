"use client";

import React, { useEffect, useState, useRef } from "react";
import { useInView, useReducedMotion } from "framer-motion";
import { Sparkles, Mic2, Target, Zap, Clock, ShieldCheck } from "lucide-react";
import SectionReveal from "./ui/SectionReveal";

function CounterItem({ value, suffix = "", prefix = "", label, sublabel, icon: Icon }) {
  const ref = useRef(null);
  const isInView = useInView(ref, { once: true, margin: "-40px" });
  const shouldReduceMotion = useReducedMotion();
  const [displayValue, setDisplayValue] = useState(0);

  const numericValue = typeof value === "number" ? value : parseInt(value, 10);

  useEffect(() => {
    if (!isInView || isNaN(numericValue) || shouldReduceMotion) {
      if (isInView) setDisplayValue(numericValue);
      return;
    }

    let start = 0;
    const duration = 1400; // ms
    const stepTime = 25;
    const steps = duration / stepTime;
    const increment = numericValue / steps;

    const timer = setInterval(() => {
      start += increment;
      if (start >= numericValue) {
        setDisplayValue(numericValue);
        clearInterval(timer);
      } else {
        setDisplayValue(Math.floor(start));
      }
    }, stepTime);

    return () => clearInterval(timer);
  }, [isInView, numericValue, shouldReduceMotion]);

  return (
    <div
      ref={ref}
      className="relative rounded-2xl border border-[#E8E8F2] dark:border-white/10 bg-white dark:bg-[#121021] p-6 shadow-sm hover:shadow-md transition-all duration-300 group"
    >
      <div className="flex items-center justify-between mb-3">
        <div className="flex h-10 w-10 items-center justify-center rounded-xl bg-brand-lavender dark:bg-white/5 text-brand-primary group-hover:scale-105 transition-transform duration-200">
          <Icon className="h-5 w-5" />
        </div>
        <span className="text-[11px] font-semibold text-emerald-500 bg-emerald-500/10 px-2 py-0.5 rounded-full">
          Verified
        </span>
      </div>

      <div className="flex items-baseline gap-0.5 mb-1">
        {prefix && (
          <span className="text-2xl sm:text-3xl font-bold text-brand-dark dark:text-white">
            {prefix}
          </span>
        )}
        <span className="text-3xl sm:text-4xl font-extrabold tracking-tight text-brand-dark dark:text-white">
          {shouldReduceMotion ? numericValue : displayValue}
        </span>
        {suffix && (
          <span className="text-2xl sm:text-3xl font-bold text-brand-primary">
            {suffix}
          </span>
        )}
      </div>

      <h4 className="text-sm font-bold text-brand-dark dark:text-white mb-0.5">
        {label}
      </h4>
      <p className="text-xs text-brand-muted dark:text-neutral-400 leading-relaxed">
        {sublabel}
      </p>
    </div>
  );
}

